import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { post } from "../../../packages/kernel/src/journal.ts";

const source = new URL("../../../evidence/spike2-log.masked.jsonl", import.meta.url);
const target = new URL("../lib/replay-postings.ts", import.meta.url);
const events = (await readFile(source, "utf8")).trim().split(/\r?\n/).map(JSON.parse);
const authorization = events.find(row => row.step === "authorize C");
const auth = authorization?.body.purchase_units[0].payments.authorizations[0];
assert.equal(authorization?.status, 201);
assert.equal(auth?.status, "CREATED");
assert.equal(auth.amount.currency_code, "USD");
const captures = events.filter(row => /^C capture #\d+ 1\.00$/.test(row.step));
assert.equal(captures.length, 12);
const voidResponse = events.find(row => row.step === "C void remainder");
assert.equal(voidResponse?.status, 200);
assert.equal(voidResponse.body.status, "VOIDED");
assert.equal(voidResponse.body.id, auth.id);

function minor(amount) {
  assert.equal(amount.currency_code, "USD");
  assert.match(amount.value, /^\d+\.\d\d$/);
  return BigInt(amount.value.replace(".", ""));
}

const lease = "20000000-0000-4000-8000-000000000001";
const postings = [];
const sink = { async query(sql, [, leaseId, kind, ref, serialized]) {
  assert.match(sql, /insert into public\.ledger_entries/);
  assert.equal(leaseId, lease);
  const legs = JSON.parse(serialized).map(line => [line.account, line.direction, line.amount]);
  postings.push({ kind, ref, legs });
} };

const cap = minor(auth.amount);
await post(sink, lease, "authorize", auth.id, cap);
let captured = 0n;
for (const row of captures) {
  const { body } = row;
  assert.equal(row.status, 201);
  assert.equal(row.path, `/v2/payments/authorizations/${auth.id}/capture`);
  assert.equal(body.status, "COMPLETED");
  const amount = minor(body.amount);
  const fee = minor(body.seller_receivable_breakdown.paypal_fee);
  await post(sink, lease, "commit", body.id, amount);
  await post(sink, lease, "capture", body.id, amount, null, fee);
  captured += amount;
}
assert(captured <= cap);
await post(sink, lease, "void", voidResponse.body.id, cap - captured);

const generated = "// Generated by scripts/replay-proof.mjs through kernel post().\n" +
  `export const replayLeaseId = ${JSON.stringify(lease)};\nexport const replayPostings = [\n` +
  postings.map(group => "  " + JSON.stringify(group) + ",").join("\n") + "\n] as const;\n";

if (process.argv.includes("--check")) assert.equal(await readFile(target, "utf8"), generated);
else await writeFile(target, generated);
console.log(`PASS kernel replay: ${postings.length} posting groups, ${captures.length} captures and one void`);

